import { z } from "zod";

export const GroundedAiLibraryIdSchema = z
  .string()
  .trim()
  .min(1)
  .max(64)
  .regex(/^[a-z0-9][a-z0-9_-]*$/);
export type GroundedAiLibraryId = z.infer<typeof GroundedAiLibraryIdSchema>;

/** Covers 30 planned evidence chunks plus verified AMBOSS neighbors. */
export const MAX_GROUNDED_CITATIONS = 60;
/** Up to four 50-hit searches and ten verified AMBOSS R2 neighbors. */
export const MAX_VERIFIED_EVIDENCE_SOURCES = 220;

export const SantoSourceModeSchema = z.enum(["libraries", "research"]);
export type SantoSourceMode = z.infer<typeof SantoSourceModeSchema>;

export const GroundedAiQueryRequestSchema = z
  .object({
    query: z.string().trim().min(1).max(4000),
    idempotency_key: z.string().trim().min(1).max(128),
    library_id: GroundedAiLibraryIdSchema.optional(),
    source_mode: SantoSourceModeSchema.optional(),
    /** Trusted Qwen-only replies from ConversationDO; no Luna outputs. */
    recent_qwen_replies: z
      .array(
        z
          .object({ sequence: z.number().int().nonnegative(), answer: z.string().max(350) })
          .strict(),
      )
      .max(5)
      .optional(),
    /** Optional bounded router context; constructed by trusted ConversationDO on /ask. */
    recent_user_messages: z.array(z.string().max(1000)).max(5).optional(),
  })
  .strict();
export type GroundedAiQueryRequest = z.infer<typeof GroundedAiQueryRequestSchema>;

export const GroundedAiCitationSchema = z.object({
  sourceId: z.string().min(1).max(512),
  title: z.string().min(1).max(500),
  page: z.number().int().positive().nullable(),
});
export type GroundedAiCitation = z.infer<typeof GroundedAiCitationSchema>;

/** Verified gallery figures are visual aids, NEVER sources for clinical claims.
 * The URL is an immutable R2 media asset from the backend image manifest.
 */
/** PMC OA 2026 cloud objects: accept only version-pinned figure files with a
 * metadata-declared MD5, never browser/model-provided off-domain URLs. */
export function approvedPmcFigureImageUrl(value: string): boolean {
  if (typeof value !== "string" || value.length > 900 || /\/(?:\.{2}|%2e%2e)\//i.test(value)) return false;
  try {
    const url = new URL(value);
    return (
      url.origin === "https://pmc-oa-opendata.s3.amazonaws.com" &&
      !url.username &&
      !url.password &&
      !url.hash &&
      /^\/PMC[1-9]\d{0,11}\.[1-9]\d{0,2}\/[A-Za-z0-9_.-]+\.(?:jpg|jpeg|png|webp|gif)$/i.test(
        url.pathname,
      ) &&
      /^md5=[a-f0-9]{32}$/i.test(url.search.slice(1))
    );
  } catch {
    return false;
  }
}

export const GroundedAiRelatedPicSchema = z
  .object({
    src: z
      .string()
      .max(900)
      .refine(
        (value) =>
          /^https:\/\/pub-2a81f2cb19cc4473a3d076e657af6121\.r2\.dev\/offline_media\/[A-Za-z0-9_%+.-]+\.(?:png|jpg|jpeg|webp|gif)$/i.test(
            value,
          ) || approvedPmcFigureImageUrl(value),
        "Only authorized R2 or licensed PMC version-pinned image URLs are accepted",
      ),
    alt: z.string().min(1).max(160),
    caption: z.string().max(240),
    sourceName: z.string().min(1).max(160),
  })
  .strict();
export type GroundedAiRelatedPic = z.infer<typeof GroundedAiRelatedPicSchema>;

export const GroundedAiSuggestedFlashcardSchema = z
  .object({
    cardId: z.number().int().positive().safe(),
    ankiQuery: z.string().regex(/^cid:[0-9]{10,16}$/),
    focus: z.string().min(1).max(180),
    preview: z.string().min(1).max(500),
    /** Source-backed complete revealed text, never generated by Luna. */
    backText: z.string().min(1).max(2500).optional(),
    /** Displayable owner-cleared AnKing note fields, never internal IDs/tags. */
    noteFields: z
      .array(
        z
          .object({
            label: z.string().min(1).max(80),
            value: z.string().min(1).max(3000),
          })
          .strict(),
      )
      .max(12)
      .optional(),
  })
  .strict()
  .refine((card) => card.ankiQuery === `cid:${card.cardId}`, {
    message: "Anki query must equal the canonical server-provided Card ID",
  });
export type GroundedAiSuggestedFlashcard = z.infer<typeof GroundedAiSuggestedFlashcardSchema>;

export const GroundedAiUsageSchema = z.object({
  unitsCharged: z.literal(1),
  remaining: z.number().int().nonnegative(),
});
export type GroundedAiUsage = z.infer<typeof GroundedAiUsageSchema>;

export const GroundedAiQueryResponseSchema = z
  .object({
    requestId: z.string().uuid(),
    messageId: z.string().uuid(),
    answer: z.string().min(1),
    /** Only for genuine Qwen CHAT/CLARIFY turns; Luna never sets this. */
    responder: z.literal("qwen").optional(),
    /** Legacy responses without this property are always source-grounded. */
    groundingMode: z.enum(["santo", "general"]).optional(),
    citations: z.array(GroundedAiCitationSchema).max(MAX_GROUNDED_CITATIONS),
    /** Optional persisted candidates not selected for inline Luna figures. */
    relatedPics: z.array(GroundedAiRelatedPicSchema).max(50).optional(),
    /** Exact backend-owned AnKing CIDs; not model-generated clinical citations. */
    suggestedFlashcards: z.array(GroundedAiSuggestedFlashcardSchema).max(5).optional(),
    /** Real browsable library articles, but not model-cited inline medical claims. */
    citationMode: z.literal("related").optional(),
    usage: GroundedAiUsageSchema,
  })
  .superRefine((response, ctx) => {
    const general = response.groundingMode === "general";
    if (general && response.citationMode) {
      ctx.addIssue({
        code: "custom",
        path: ["citationMode"],
        message: "General answers cannot have related Santo source lists",
      });
    }
    if (general && response.citations.length !== 0) {
      ctx.addIssue({
        code: "custom",
        path: ["citations"],
        message: "General answers cannot have Santo citations",
      });
    }
    if (!general && response.citations.length === 0) {
      ctx.addIssue({
        code: "custom",
        path: ["citations"],
        message: "Grounded answers must cite a verified Santo source",
      });
    }
  });
export type GroundedAiQueryResponse = z.infer<typeof GroundedAiQueryResponseSchema>;

/**
 * SSE frames for the buffered verified stream. No event is sent before
 * grounded citations are server-validated and quota is finalized.
 */
export const GroundedAiStreamDeltaSchema = z
  .object({
    type: z.literal("delta"),
    requestId: z.string().uuid(),
    messageId: z.string().uuid(),
    index: z.number().int().nonnegative(),
    text: z.string().min(1).max(360),
  })
  .strict();

export const GroundedAiStreamCompleteSchema = z
  .object({
    type: z.literal("complete"),
    response: GroundedAiQueryResponseSchema,
  })
  .strict();

export const GroundedAiStreamEventSchema = z.discriminatedUnion("type", [
  GroundedAiStreamDeltaSchema,
  GroundedAiStreamCompleteSchema,
]);
export type GroundedAiStreamEvent = z.infer<typeof GroundedAiStreamEventSchema>;
